const withChecksum = (first14) => first14 + gstinCheckChar(first14);
const esc = (s) => String(s ?? "").replace(/&/g, "&amp;").replace(/</g, "&lt;").replace(/>/g, "&gt;");
const money = (n) => `Rs. ${Number(n).toLocaleString("en-IN", { minimumFractionDigits: 2, maximumFractionDigits: 2 })}`;

async function invoiceImage(o) {
  const t = (x, y, size, fill, text, anchor = "start") =>
    `<text x="${x}" y="${y}" font-family="Arial, Helvetica, sans-serif" font-size="${size}" fill="${fill}" text-anchor="${anchor}">${esc(text)}</text>`;
  let s = `<svg xmlns="http://www.w3.org/2000/svg" width="1200" height="1600"><rect width="1200" height="1600" fill="#fff"/>`;
  s += `<rect width="1200" height="140" fill="#1E3A8A"/>` + t(60, 85, 40, "#fff", "TAX INVOICE");
  s += t(800, 70, 28, "#fff", `Invoice #: ${o.number}`) + t(800, 110, 22, "#93C5FD", `Date: ${o.date}`);
  s += `<rect x="60" y="180" width="500" height="180" fill="#F8FAFC" stroke="#CBD5E1" stroke-width="2"/>`;
  s += t(80, 215, 20, "#1E3A8A", "SUPPLIER (ISSUER):") + t(80, 252, 22, "#0F172A", o.supplier) + t(80, 287, 20, "#334155", `GSTIN: ${o.supplierGstin}`);
  s += `<rect x="640" y="180" width="500" height="180" fill="#F8FAFC" stroke="#CBD5E1" stroke-width="2"/>`;
  s += t(660, 215, 20, "#1E3A8A", "BILLED TO (RECIPIENT):") + t(660, 252, 22, "#0F172A", o.buyer) + t(660, 287, 20, "#334155", `GSTIN: ${o.buyerGstin || "UNREGISTERED CONSUMER"}`);
  s += `<rect x="60" y="620" width="1080" height="45" fill="#E2E8F0"/>`;
  [[80, "#"], [140, "Description"], [540, "HSN"], [660, "Qty"], [760, "Rate"], [950, "Taxable Amount"]].forEach(([x, h]) => (s += t(x, 650, 18, "#1E293B", h)));
  let y = 700;
  o.items.forEach((it, i) => {
    s += t(80, y, 18, "#334155", i + 1) + t(140, y, 18, "#0F172A", it.description.slice(0, 36)) + t(540, y, 18, "#334155", it.hsn_sac);
    s += t(660, y, 18, "#334155", `${it.quantity} ${it.unit}`) + t(760, y, 18, "#334155", money(it.rate)) + t(950, y, 18, "#0F172A", money(it.taxable_value));
    s += `<line x1="60" y1="${y + 15}" x2="1140" y2="${y + 15}" stroke="#E2E8F0"/>`;
    y += 50;
  });
  s += `<rect x="640" y="1180" width="500" height="260" fill="#F8FAFC" stroke="#CBD5E1" stroke-width="2"/>`;
  s += t(660, 1220, 20, "#475569", "Total Taxable Value:") + t(950, 1220, 20, "#0F172A", money(o.taxable));
  if (o.cgst > 0) {
    s += t(660, 1260, 18, "#475569", "Central Tax (CGST 9%):") + t(950, 1260, 18, "#0F172A", money(o.cgst));
    s += t(660, 1300, 18, "#475569", "State Tax (SGST 9%):") + t(950, 1300, 18, "#0F172A", money(o.sgst));
  } else if (o.igst > 0) {
    s += t(660, 1260, 18, "#475569", "Integrated Tax (IGST 18%):") + t(950, 1260, 18, "#0F172A", money(o.igst));
  }
  s += t(660, 1385, 24, "#1E3A8A", "GRAND TOTAL:") + t(930, 1385, 24, "#1E3A8A", money(o.total));
  s += t(60, 1530, 16, "#94A3B8", "Sample invoice generated by GST Invoice Automator seed data") + "</svg>";
  return sharp(Buffer.from(s)).png().toBuffer();
}

const line = (description, hsn_sac, quantity, unit, rate, taxable, rateTax, kind) => ({
  description, hsn_sac, quantity, unit, rate, taxable_value: taxable,
  cgst_rate: kind === "intra" ? rateTax / 2 : 0, cgst_amount: kind === "intra" ? (taxable * rateTax) / 200 : 0,
  sgst_rate: kind === "intra" ? rateTax / 2 : 0, sgst_amount: kind === "intra" ? (taxable * rateTax) / 200 : 0,
  igst_rate: kind === "inter" ? rateTax : 0, igst_amount: kind === "inter" ? (taxable * rateTax) / 100 : 0, cess: 0,
});

